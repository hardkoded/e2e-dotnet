// Writes app/report.ts: the `Report` type the page reads, generated from schema/report-v1.schema.json.
// .NET-only: upstream's page imports `Report` from the `e2e` package, which the port has no npm counterpart of.
import { readFile, writeFile } from 'node:fs/promises';
import { compile } from 'json-schema-to-typescript';

const schemaPath = new URL('../../../schema/report-v1.schema.json', import.meta.url);
const schema = JSON.parse(await readFile(schemaPath, 'utf8'));
schema.title = 'Report';
const types = await compile(schema, 'Report', {
  bannerComment: '/* Generated by scripts/generate-report-types.mjs from schema/report-v1.schema.json. Do not edit. */',
  additionalProperties: false,
  unknownAny: true,
  strictIndexSignatures: true,
  format: false,
});
await writeFile(new URL('../app/report.ts', import.meta.url), types.replace(/^export interface Report /mu, 'export interface Report '));
