using System.Text.Json;
using System.Text.RegularExpressions;
using E2E.Engine;
using E2E.Tests.Crosscheck;
using Microsoft.Playwright;
using Expectations = E2E.Tests.Crosscheck.CrosscheckExpectations;

namespace E2E.Tests.Conformance;

/// <summary>
/// Ported from upstream's <c>conformance.test.ts</c>, <c>describe('axe-core conformance')</c>: the engine's roles and accessible
/// names against the expectations the axe-core test suite states for the same markup (<c>axe-core/</c>). Every target of every
/// case is checked; what the engine reads differently must be listed in <c>expected.txt</c> with a reason, and a listed case that
/// now agrees fails too. <c>E2E_CROSSCHECK_UPDATE=1</c> rewrites the file the way it rewrites the cross-check's. The tests share
/// one page and the results it records, so the expectations test runs last.
/// </summary>
[Collection(BrowserCollection.Name)]
[TestCaseOrderer("E2E.Tests.Crosscheck.ExpectationsLastOrderer", "E2E.Tests")]
public sealed partial class AxeCoreConformanceTests(AxePage axe) : IClassFixture<AxePage>
{
    private static readonly string Header = string.Join(
        '\n',
        "# Cases where the engine reads markup differently from what the axe-core suite expects, one per line:",
        "# page | oracle field | case target | ours <value> | theirs <value> | reason",
        "# Generated by E2E_CROSSCHECK_UPDATE=1; edit only the reasons. See tests/E2E.Tests/Crosscheck/CrosscheckExpectations.cs."
    );

    private static readonly bool Update = Environment.GetEnvironmentVariable("E2E_CROSSCHECK_UPDATE") == "1";

    /// <summary>
    /// The cases are markup without layout, and the tree lists only what has a box: an empty element gets a one-pixel one, as the
    /// reader's own role tests do, so a role is read rather than a zero-size element skipped.
    /// </summary>
    private const string EmptyBoxes = "<style>:empty { min-width: 1px; min-height: 1px }</style>";

    /// <summary>axe spells an open shadow root as <c>&lt;template shadow&gt;</c>; this attaches each one, as Playwright's runner of these cases does.</summary>
    private const string ShadowTemplates = """
        <script>
          for (const template of document.querySelectorAll('template[shadow]')) {
            template.parentElement.attachShadow({ mode: 'open' }).appendChild(template.content);
            template.remove();
          }
        </script>
        """;

    /// <summary>Roles the tree spells its own way, and the roles that mean "no role" to axe.</summary>
    private static readonly Dictionary<string, string> AsAria = new() { ["image"] = "img" };

    private static readonly HashSet<string> NoRole = ["generic", "none", "presentation", "text"];

    [GeneratedRegex(@"\s+")]
    private static partial Regex Whitespace();

    // The test runs from the build output; the files are the ones in the source tree, found by the solution file beside tests/.
    private static string SourceDirectory()
    {
        for (
            var directory = new DirectoryInfo(AppContext.BaseDirectory);
            directory is not null;
            directory = directory.Parent
        )
        {
            if (File.Exists(Path.Combine(directory.FullName, "E2E.slnx")))
            {
                return Path.Combine(directory.FullName, "tests", "E2E.Tests", "Conformance");
            }
        }

        throw new InvalidOperationException("E2E.slnx not found above the test output.");
    }

    private static string Normalize(string? text) => Whitespace().Replace(text ?? "", " ").Trim();

    private static List<JsonElement> AsList(JsonElement value) =>
        value.ValueKind == JsonValueKind.Array ? [.. value.EnumerateArray()] : [value];

    private async Task CheckTableAsync(string table)
    {
        var cases = JsonDocument.Parse(File.ReadAllText(Path.Combine(SourceDirectory(), "axe-core", $"{table}.json")));
        var name = $"axe: {table}";
        axe.Pages.Add(name);
        var checkedCount = 0;
        var targets = 0;
        var index = -1;
        foreach (var entry in cases.RootElement.EnumerateArray())
        {
            index++;
            await axe.Page.SetContentAsync(
                $"""<!doctype html><html lang="en"><head>{EmptyBoxes}</head><body>{entry.GetProperty("html").GetString()}{ShadowTemplates}</body></html>"""
            );
            var (nodes, _) = await E2E.Tests.Crosscheck.Crosscheck.CaptureTaggedAsync(axe.Page);
            var byId = nodes.ToDictionary(node => node.Id, StringComparer.Ordinal);
            var selectors = AsList(entry.GetProperty("target"));
            var hasText = entry.TryGetProperty("accessibleText", out var accessibleText);
            var texts = hasText ? AsList(accessibleText) : [];
            var hasRole = entry.TryGetProperty("role", out var expectedRole);
            for (var position = 0; position < selectors.Count; position++)
            {
                var selector = selectors[position].GetString()!;
                targets++;
                var target = axe.Page.Locator(selector).First;
                Assert.True(await target.CountAsync() == 1, $"{table} #{index}: {selector} matches nothing");
                var id = await target.GetAttributeAsync(E2E.Tests.Crosscheck.Crosscheck.Marker);
                CheckNode? node = id is not null && byId.TryGetValue(id, out var found) ? found : null;
                var label = $"#{index} {selector}";

                void Push(string field, string ours, string theirs) =>
                    axe.Seen.Add(Expectations.KeyOf(name, new Disagreement("axe", field, ours, theirs, label)));

                if (hasRole)
                {
                    // A node the tree does not list has no role to the model either.
                    var ours =
                        node?.Role is null || NoRole.Contains(node.Role)
                            ? "none"
                            : AsAria.GetValueOrDefault(node.Role, node.Role);
                    var theirs =
                        expectedRole.ValueKind == JsonValueKind.Null || NoRole.Contains(expectedRole.GetString()!)
                            ? "none"
                            : expectedRole.GetString()!;
                    if (ours != theirs)
                    {
                        Push("role", ours, theirs);
                    }

                    checkedCount++;
                }

                if (hasText)
                {
                    var ours = node is null ? "(not in tree)" : Normalize(node.Name);
                    var theirs = Normalize(position < texts.Count ? texts[position].GetString() : "");
                    if (ours != theirs)
                    {
                        Push("name", ours, theirs);
                    }

                    checkedCount++;
                }
            }
        }

        Assert.True(checkedCount > 0, $"{table} checked nothing");
        Assert.Equal(targets, checkedCount);
    }

    [Fact]
    public Task Implicit_role_every_case() => CheckTableAsync("implicit-role");

    [Fact]
    public Task Accessible_text_every_case() => CheckTableAsync("accessible-text");

    [Fact]
    public void Matches_the_expectations()
    {
        var expectedPath = Path.Combine(SourceDirectory(), "expected.txt");
        var expected = Expectations.ReadExpectations(expectedPath);
        if (Update)
        {
            Expectations.WriteExpectations(expectedPath, Header, expected, axe.Seen, axe.Pages);
            return;
        }

        var (unexpected, stale) = Expectations.DiffExpectations(expected, axe.Seen, axe.Pages);
        var todo = expected.Where(entry => entry.Value == Expectations.TodoReason).Select(entry => entry.Key).ToList();
        Assert.True(
            unexpected.Count == 0 && stale.Count == 0 && todo.Count == 0,
            "rerun with E2E_CROSSCHECK_UPDATE=1 and review the diff of tests/E2E.Tests/Conformance/expected.txt\n"
                + $"unexpected:\n{string.Join('\n', unexpected)}\nstale:\n{string.Join('\n', stale)}\ntodo:\n{string.Join('\n', todo)}"
        );
    }
}

/// <summary>
/// One Chromium and one page, in a context that records closed shadow roots at creation, for the tests of
/// <see cref="AxeCoreConformanceTests"/>, opened once as upstream's <c>beforeAll</c> does, with the disagreements and pages the
/// tests record. .NET-only: xUnit builds a test class per test, so the shared state lives here.
/// </summary>
public sealed class AxePage : IAsyncLifetime
{
    private IPlaywright? _playwright;
    private IBrowser? _browser;

    public IPage Page { get; private set; } = null!;

    public HashSet<string> Seen { get; } = new(StringComparer.Ordinal);

    public HashSet<string> Pages { get; } = new(StringComparer.Ordinal);

    public async Task InitializeAsync()
    {
        await WebEngine.EnsureChromiumAsync(headed: false, CancellationToken.None);
        _playwright = await Playwright.CreateAsync();
        try
        {
            _browser = await _playwright.Chromium.LaunchAsync(new BrowserTypeLaunchOptions { Headless = true });
            var context = await _browser.NewContextAsync();
            await context.AddInitScriptAsync(PageScript.RecordClosedShadowRoots);
            Page = await context.NewPageAsync();
        }
        catch
        {
            // xUnit does not call DisposeAsync when InitializeAsync throws.
            await DisposeAsync();
            throw;
        }
    }

    public async Task DisposeAsync()
    {
        try
        {
            if (_browser is not null)
            {
                await _browser.CloseAsync();
            }
        }
        finally
        {
            _playwright?.Dispose();
        }
    }
}
