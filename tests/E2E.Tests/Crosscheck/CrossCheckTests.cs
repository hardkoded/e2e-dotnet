using Microsoft.Playwright;

namespace E2E.Tests.Crosscheck;

/// <summary>
/// Ported from upstream's <c>crosscheck.test.ts</c>: the engine's tree against Chrome's accessibility tree and Playwright's
/// <c>getByRole</c> on the fixture pages, and on every web-benchmark scenario when <c>CROSSCHECK_BENCHMARK_URL</c> names a running
/// benchmark app. Disagreements must match <c>expected.txt</c>; <c>E2E_CROSSCHECK_UPDATE=1</c> rewrites it (see
/// <see cref="CrosscheckExpectations"/>). The tests share one page and the results it records, so the expectations test runs last.
/// </summary>
[Collection(BrowserCollection.Name)]
[TestCaseOrderer("E2E.Tests.Crosscheck.ExpectationsLastOrderer", "E2E.Tests")]
public sealed partial class CrossCheckTests(CheckPage check) : IClassFixture<CheckPage>
{
    private static readonly string Header = string.Join(
        '\n',
        "# Known disagreements between the engine tree and Chrome or Playwright, one per line:",
        "# page | oracle field | role \"name\" | ours <value> | theirs <value> | reason",
        "# Generated by E2E_CROSSCHECK_UPDATE=1; edit only the reasons. See tests/E2E.Tests/Crosscheck/CrosscheckExpectations.cs."
    );

    private static readonly bool Update = Environment.GetEnvironmentVariable("E2E_CROSSCHECK_UPDATE") == "1";

    public static TheoryData<string> FixtureNames() =>
        [.. CrosscheckFixtures.FixturePages.Select(fixture => fixture.Name)];

    // The test runs from the build output; expected.txt is the one in the source tree, found by the solution file beside tests/.
    private static string ExpectedPath()
    {
        for (
            var directory = new DirectoryInfo(AppContext.BaseDirectory);
            directory is not null;
            directory = directory.Parent
        )
        {
            if (File.Exists(Path.Combine(directory.FullName, "E2E.slnx")))
            {
                return Path.Combine(directory.FullName, "tests", "E2E.Tests", "Crosscheck", "expected.txt");
            }
        }

        throw new InvalidOperationException("E2E.slnx not found above the test output.");
    }

    /// <summary>Checks the page as loaded and records its disagreements under <paramref name="name"/>.</summary>
    private async Task CheckAsync(string name)
    {
        var result = await Crosscheck.CrossCheckAsync(check.Page);
        Assert.True(result.Compared > 0, $"{name} compared no node");
        check.Pages.Add(name);
        foreach (var disagreement in result.Disagreements)
        {
            check.Seen.Add(CrosscheckExpectations.KeyOf(name, disagreement));
        }
    }

    [Theory]
    [MemberData(nameof(FixtureNames))]
    public async Task Fixture(string name)
    {
        var fixture = CrosscheckFixtures.FixturePages.Single(page => page.Name == name);
        await check.Page.SetContentAsync($"""<!doctype html><html lang="en"><body>{fixture.Html}</body></html>""");
        await CheckAsync($"fixture: {fixture.Name}");
    }

    [Fact]
    public void Matches_the_expectations()
    {
        var expectedPath = ExpectedPath();
        var expected = CrosscheckExpectations.ReadExpectations(expectedPath);
        if (Update)
        {
            CrosscheckExpectations.WriteExpectations(expectedPath, Header, expected, check.Seen, check.Pages);
            return;
        }

        var (unexpected, stale) = CrosscheckExpectations.DiffExpectations(expected, check.Seen, check.Pages);
        var todo = expected
            .Where(entry =>
                check.Pages.Contains(CrosscheckExpectations.PageOf(entry.Key))
                && entry.Value == CrosscheckExpectations.TodoReason
            )
            .Select(entry => entry.Key)
            .ToList();
        Assert.True(
            unexpected.Count == 0 && stale.Count == 0 && todo.Count == 0,
            "rerun with E2E_CROSSCHECK_UPDATE=1 and review the diff of tests/E2E.Tests/Crosscheck/expected.txt\n"
                + $"unexpected:\n{string.Join('\n', unexpected)}\nstale:\n{string.Join('\n', stale)}\ntodo:\n{string.Join('\n', todo)}"
        );
    }
}

/// <summary>
/// One Chromium and one check page for the tests of <see cref="CrossCheckTests"/>, opened once as upstream's <c>beforeAll</c> does,
/// with the disagreements and pages the tests record. .NET-only: xUnit builds a test class per test, so the shared state lives here.
/// </summary>
public sealed class CheckPage : IAsyncLifetime
{
    private IPlaywright? _playwright;
    private IBrowser? _browser;

    public IPage Page { get; private set; } = null!;

    public HashSet<string> Seen { get; } = new(StringComparer.Ordinal);

    public HashSet<string> Pages { get; } = new(StringComparer.Ordinal);

    public async Task InitializeAsync()
    {
        await E2E.Engine.WebEngine.EnsureChromiumAsync(headed: false, CancellationToken.None);
        _playwright = await Playwright.CreateAsync();
        _browser = await _playwright.Chromium.LaunchAsync(new BrowserTypeLaunchOptions { Headless = true });
        Page = await Crosscheck.OpenCheckPageAsync(_browser);
    }

    public async Task DisposeAsync()
    {
        if (_browser is not null)
        {
            await _browser.CloseAsync();
        }

        _playwright?.Dispose();
    }
}
